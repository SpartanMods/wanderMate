/**
 * Generates supabase/migrations/20260605000002_seed_zones.sql
 * from data/tripZones.ts via the existing TS loader.
 *
 * Run: node --import ./scripts/register-loader.mjs scripts/generate-zones-seed.mjs
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

// Use dynamic import so the TS loader resolves the alias
const { default: tripZones } = await import("../data/tripZones.ts");

function sqlStr(val) {
  if (val === null || val === undefined) return "NULL";
  return `'${String(val).replace(/'/g, "''")}'`;
}

function sqlJson(val) {
  if (val === null || val === undefined) return "NULL";
  return `'${JSON.stringify(val).replace(/'/g, "''")}'::jsonb`;
}

function sqlArray(arr) {
  if (!arr || arr.length === 0) return "'{}'";
  return `ARRAY[${arr.map(sqlStr).join(", ")}]`;
}

function sqlGeom(coords) {
  if (!coords) return "NULL";
  return `ST_SetSRID(ST_MakePoint(${coords.lng}, ${coords.lat}), 4326)`;
}

const inserts = tripZones.map((z) => {
  // Full document stored in data column (everything the app needs)
  const doc = {
    summary: z.summary,
    generalArea: z.generalArea,
    activities: z.activities,
    skillLevel: z.skillLevel,
    minRecommendedSkill: z.minRecommendedSkill,
    offGridLevel: z.offGridLevel,
    crowdLevel: z.crowdLevel,
    hiddenGemScore: z.hiddenGemScore,
    popularityScore: z.popularityScore,
    vehicleRequirement: z.vehicleRequirement,
    campingTypes: z.campingTypes,
    driveTimeFromDenverHours: z.driveTimeFromDenverHours,
    bestSeasons: z.bestSeasons,
    vibes: z.vibes,
    avoidFlags: z.avoidFlags,
    watchouts: z.watchouts,
    safetyNotes: z.safetyNotes,
    suggestedItinerary: z.suggestedItinerary,
    backupOptions: z.backupOptions,
    sourceLinks: z.sourceLinks,
    dataConfidence: z.dataConfidence,
    landManager: z.landManager,
    dataQuality: z.dataQuality,
    sensitiveLocationLevel: z.sensitiveLocationLevel,
    roadAccess: z.roadAccess,
    legality: z.legality,
    remoteness: z.remoteness,
    verificationLinks: z.verificationLinks,
  };

  return `insert into zones (id, name, state, region, skill_level, vehicle_requirement, drive_time_from_denver_hours, off_grid_level, crowd_level, hidden_gem_score, best_seasons, camping_types, coordinates, data)
values (
  ${sqlStr(z.id)},
  ${sqlStr(z.name)},
  ${sqlStr(z.state)},
  ${sqlStr(z.region)},
  ${sqlStr(z.skillLevel)},
  ${sqlStr(z.vehicleRequirement)},
  ${z.driveTimeFromDenverHours},
  ${z.offGridLevel},
  ${z.crowdLevel},
  ${z.hiddenGemScore},
  ${sqlArray(z.bestSeasons)},
  ${sqlArray(z.campingTypes)},
  ${sqlGeom(z.coordinates)},
  ${sqlJson(doc)}
)
on conflict (id) do update set
  name = excluded.name,
  state = excluded.state,
  region = excluded.region,
  skill_level = excluded.skill_level,
  vehicle_requirement = excluded.vehicle_requirement,
  drive_time_from_denver_hours = excluded.drive_time_from_denver_hours,
  off_grid_level = excluded.off_grid_level,
  crowd_level = excluded.crowd_level,
  hidden_gem_score = excluded.hidden_gem_score,
  best_seasons = excluded.best_seasons,
  camping_types = excluded.camping_types,
  coordinates = excluded.coordinates,
  data = excluded.data,
  updated_at = now();`;
});

const sql = `-- Seed zones from tripZones.ts (auto-generated by scripts/generate-zones-seed.mjs)
-- Re-run the generator after editing data/tripZones.ts.

${inserts.join("\n\n")}
`;

const outPath = new URL("../supabase/migrations/20260605000002_seed_zones.sql", import.meta.url);
writeFileSync(outPath, sql, "utf8");
console.log(`✓ Written ${tripZones.length} zones to ${outPath.pathname}`);
